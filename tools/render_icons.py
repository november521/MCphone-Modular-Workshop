"""Export the source vector App icons to PNG. Requires Pillow only when regenerating art."""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'shared/src/main/resources/assets/mcphone_workshop/textures/app'
SOURCE = ROOT / 'art/icons'


def render(name, background, shapes):
    image = Image.new('RGBA', (256, 256))
    draw = ImageDraw.Draw(image)
    svg = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">',
           f'<rect width="64" height="64" rx="12" fill="{background}"/>']
    draw.rounded_rectangle((0, 0, 255, 255), 48, fill=background)
    for color, points in shapes:
        draw.polygon([(x * 4, y * 4) for x, y in points], fill=color)
        svg.append(f'<polygon fill="{color}" points="' + ' '.join(f'{x},{y}' for x, y in points) + '"/>')
    OUT.mkdir(parents=True, exist_ok=True)
    SOURCE.mkdir(parents=True, exist_ok=True)
    (SOURCE / f'{name}.svg').write_text('\n'.join(svg + ['</svg>']) + '\n', encoding='utf-8')
    image.resize((128, 128), Image.Resampling.LANCZOS).save(OUT / f'{name}.png')


